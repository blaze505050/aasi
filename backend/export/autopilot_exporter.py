"""
AASI UAV & Drone Autopilot Tuning Parameter Exporter.

Bridges the aerodynamic database directly into PX4 Autopilot and ArduPilot (Plane)
flight control configurations. Eliminates weeks of manual controller gain estimation
for fixed-wing UAVs, hybrid eVTOLs, and drone airframes.
"""

from __future__ import annotations

import math
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class AirframeFlightConditions(BaseModel):
    """Airframe reference parameters for autopilot tuning."""
    mass_kg: float = Field(2.5, description="Total UAV takeoff mass in kg", ge=0.1)
    wing_span_m: float = Field(1.6, description="Wingspan in meters", ge=0.1)
    wing_area_m2: float = Field(0.38, description="Wing reference area in m²", ge=0.01)
    mean_chord_m: float = Field(0.24, description="Mean aerodynamic chord in meters", ge=0.01)
    air_density_kg_m3: float = Field(1.225, description="Ambient air density (kg/m³)", ge=0.5)
    cg_pos_ratio: float = Field(0.25, description="Center of gravity position x_cg / MAC", ge=0.0, le=1.0)


class AutopilotTuningResult(BaseModel):
    """Computed flight dynamics parameters and export decks."""
    geometry_name: str
    neutral_point_x: float
    static_margin_pct: float
    stall_speed_ms: float
    cruise_speed_ms: float
    max_speed_ms: float
    trim_alpha_deg: float
    cl_max: float
    cl_alpha_per_rad: float
    cm_alpha_per_rad: float
    px4_params_deck: str
    ardupilot_param_deck: str
    structured_parameters: Dict[str, Any]


class AutopilotExporter:
    """
    Transforms aerodynamic polars and stability derivatives into
    ready-to-flash PX4 and ArduPilot autopilot parameter decks.
    """

    @classmethod
    def compute_autopilot_parameters(
        cls,
        geometry_name: str,
        cl_alpha_per_deg: float,
        cm_alpha_per_deg: float,
        cl_max: float,
        cd0: float,
        x_ac: float = 0.25,
        alpha_zero_lift_deg: float = 0.0,
        airframe: Optional[AirframeFlightConditions] = None,
    ) -> AutopilotTuningResult:
        if airframe is None:
            airframe = AirframeFlightConditions()

        # Convert slopes to per-radian
        cl_alpha_rad = cl_alpha_per_deg * (180.0 / math.pi)
        cm_alpha_rad = cm_alpha_per_deg * (180.0 / math.pi)

        # 1. Neutral Point & Static Margin
        # Neutral point is primarily the aerodynamic center of the wing-body
        x_np = x_ac
        static_margin = (x_np - airframe.cg_pos_ratio) * 100.0  # Percentage MAC

        # 2. Speeds: Stall speed & Cruise speed
        # V_stall = sqrt( (2 * m * g) / (rho * S * CL_max) )
        weight_n = airframe.mass_kg * 9.80665
        v_stall = math.sqrt(max(1.0, (2.0 * weight_n) / (airframe.air_density_kg_m3 * airframe.wing_area_m2 * max(0.5, cl_max))))
        
        # Safe FBW minimum speed: 1.2 * V_stall
        v_min = v_stall * 1.20
        # Cruise speed (nominally at CL = 0.5 * CL_max or optimal L/D)
        cl_cruise = min(0.65, max(0.3, 0.45 * cl_max))
        v_cruise = math.sqrt((2.0 * weight_n) / (airframe.air_density_kg_m3 * airframe.wing_area_m2 * cl_cruise))
        # Max operating speed
        v_max = v_cruise * 1.65

        # 3. Trim Angle of Attack for Level Flight
        # CL_cruise = CL_alpha * (alpha_trim - alpha_0)
        alpha_trim_deg = alpha_zero_lift_deg + (cl_cruise / max(0.01, cl_alpha_per_deg))
        # Bound trim within safe linear envelope
        alpha_trim_deg = max(-2.0, min(8.0, alpha_trim_deg))

        # 4. Control Gains Estimation
        # Longitudinal pitch rate gain FW_PR_P proportional to static margin stiffness
        pitch_rate_p = max(0.02, min(0.35, 0.08 * (static_margin / 10.0)))
        # Pitch integration time
        pitch_rate_i = max(0.05, min(0.20, pitch_rate_p * 1.25))
        # Roll rate gain based on aspect ratio
        aspect_ratio = (airframe.wing_span_m ** 2) / airframe.wing_area_m2
        roll_rate_p = max(0.05, min(0.40, 0.12 * (6.0 / max(3.0, aspect_ratio))))
        
        # Max pitch angle before stall (allow 3 deg margin)
        alpha_stall_approx = max(8.0, min(18.0, (cl_max / max(0.05, cl_alpha_per_deg))))
        pitch_max_deg = max(10.0, alpha_stall_approx - 3.0)

        # 5. Build PX4 QGroundControl .params card deck
        px4_lines = [
            f"# AASI AUTONOMOUS AUTOPILOT TUNING DECK: {geometry_name.upper()}",
            f"# Generated by AASI (Autonomous Aerospace Scientific Intelligence)",
            f"# Mass: {airframe.mass_kg:.2f} kg | Span: {airframe.wing_span_m:.2f} m | MAC: {airframe.mean_chord_m:.3f} m",
            f"# Static Margin: {static_margin:.1f}% MAC | Stall Speed: {v_stall:.1f} m/s",
            f"# Format: QGroundControl PX4 Parameter Table",
            f"# Vehicle-Id\tComponent-Id\tName\tValue\tType",
            f"1\t1\tFW_AIRSPD_MIN\t{v_min:.2f}\t9",
            f"1\t1\tFW_AIRSPD_TRIM\t{v_cruise:.2f}\t9",
            f"1\t1\tFW_AIRSPD_MAX\t{v_max:.2f}\t9",
            f"1\t1\tFW_PSP_OFF\t{alpha_trim_deg:.2f}\t9",
            f"1\t1\tFW_P_RMAX_POS\t{pitch_max_deg:.1f}\t9",
            f"1\t1\tFW_P_RMAX_NEG\t20.0\t9",
            f"1\t1\tFW_PR_P\t{pitch_rate_p:.4f}\t9",
            f"1\t1\tFW_PR_I\t{pitch_rate_i:.4f}\t9",
            f"1\t1\tFW_RR_P\t{roll_rate_p:.4f}\t9",
            f"1\t1\tFW_R_RMAX\t45.0\t9",
            f"1\t1\tFW_L1_PERIOD\t17.0\t9",
            f"1\t1\tFW_W_EN\t1\t6",
        ]
        px4_deck = "\n".join(px4_lines)

        # 6. Build ArduPilot Mission Planner .param card deck
        trim_pitch_cd = int(round(alpha_trim_deg * 100))
        ardupilot_lines = [
            f"# AASI AUTOPILOT TUNING DECK: {geometry_name.upper()}",
            f"# ArduPilot Plane Parameter Export",
            f"# Mass: {airframe.mass_kg:.2f} kg | Span: {airframe.wing_span_m:.2f} m",
            f"ARSPD_FBW_MIN,{v_min:.2f}",
            f"ARSPD_FBW_CRUISE,{v_cruise:.2f}",
            f"ARSPD_FBW_MAX,{v_max:.2f}",
            f"TRIM_PITCH_CD,{trim_pitch_cd}",
            f"PTCH2SRV_P,{pitch_rate_p * 10.0:.3f}",
            f"PTCH2SRV_I,{pitch_rate_i * 8.0:.3f}",
            f"RLL2SRV_P,{roll_rate_p * 12.0:.3f}",
            f"LIM_PITCH_MAX,{int(round(pitch_max_deg * 100))}",
            f"LIM_PITCH_MIN,-2000",
            f"LIM_ROLL_CD,4500",
            f"STAB_PITCH_DOWN,{alpha_trim_deg:.1f}",
            f"NAVL1_PERIOD,18.000",
        ]
        ardupilot_deck = "\n".join(ardupilot_lines)

        structured_params = {
            "aerodynamics": {
                "cl_alpha_per_deg": cl_alpha_per_deg,
                "cm_alpha_per_deg": cm_alpha_per_deg,
                "cl_max": cl_max,
                "cd0": cd0,
                "x_ac": x_ac,
                "static_margin_pct": static_margin,
            },
            "flight_envelope": {
                "v_stall_ms": round(v_stall, 2),
                "v_min_ms": round(v_min, 2),
                "v_cruise_ms": round(v_cruise, 2),
                "v_max_ms": round(v_max, 2),
                "alpha_trim_deg": round(alpha_trim_deg, 2),
                "pitch_limit_deg": round(pitch_max_deg, 1),
            },
            "px4": {
                "FW_AIRSPD_MIN": round(v_min, 2),
                "FW_AIRSPD_TRIM": round(v_cruise, 2),
                "FW_AIRSPD_MAX": round(v_max, 2),
                "FW_PSP_OFF": round(alpha_trim_deg, 2),
                "FW_PR_P": round(pitch_rate_p, 4),
                "FW_PR_I": round(pitch_rate_i, 4),
                "FW_RR_P": round(roll_rate_p, 4),
            },
            "ardupilot": {
                "ARSPD_FBW_MIN": round(v_min, 2),
                "ARSPD_FBW_CRUISE": round(v_cruise, 2),
                "ARSPD_FBW_MAX": round(v_max, 2),
                "TRIM_PITCH_CD": trim_pitch_cd,
                "PTCH2SRV_P": round(pitch_rate_p * 10.0, 3),
                "RLL2SRV_P": round(roll_rate_p * 12.0, 3),
            },
        }

        return AutopilotTuningResult(
            geometry_name=geometry_name,
            neutral_point_x=round(x_np, 4),
            static_margin_pct=round(static_margin, 2),
            stall_speed_ms=round(v_stall, 2),
            cruise_speed_ms=round(v_cruise, 2),
            max_speed_ms=round(v_max, 2),
            trim_alpha_deg=round(alpha_trim_deg, 2),
            cl_max=round(cl_max, 3),
            cl_alpha_per_rad=round(cl_alpha_rad, 4),
            cm_alpha_per_rad=round(cm_alpha_rad, 4),
            px4_params_deck=px4_deck,
            ardupilot_param_deck=ardupilot_deck,
            structured_parameters=structured_params,
        )
