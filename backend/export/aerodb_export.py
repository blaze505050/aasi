"""
AASI Aerospace Export Engine: DATCOM, NASA S/HABP & 6-DOF Simulation Tables.

Translates verified aerodynamic database polars and stability derivatives into:
1. USAF Stability and Control DATCOM (.dat) standard card decks.
2. NASA S/HABP Tabulated Polar format (.txt/.shabp).
3. 6-DOF Flight Dynamics Simulation CSV format for Simulink, MATLAB & autopilot models.
4. Machine-readable AeroDB JSON.
"""

from __future__ import annotations

import io
import math
from typing import Any, Dict, List
from backend.physics.aerodb_engine import AeroDatabase, FlightConditionPolar


class AeroDBExporter:
    """
    Standard aerospace formats exporter for aerodynamic databases.
    """

    @classmethod
    def export_datcom(cls, db: AeroDatabase) -> str:
        """
        Exports USAF Stability and Control DATCOM standard 80-column fixed-card format.
        Compatible with JSBSim, FlightGear, and classic aerospace stability tools.
        """
        lines: List[str] = []
        lines.append(f"DIM M")
        lines.append(f"CASEID AASI AUTONOMOUS AERO DB: {db.geometry_name.upper()}")
        lines.append(f"* GENERATED BY AASI (AUTONOMOUS AEROSPACE SYSTEMS INTELLIGENCE)")
        lines.append(f"* DATABASE ID: {db.db_id}  DATE: {db.created_at_utc[:10]}")
        lines.append(f"* PROVENANCE HASH: {db.provenance_hash[:16]}")
        lines.append(f"*")

        for cond_idx, cond in enumerate(db.polars, start=1):
            mach = cond.mach
            reynolds = cond.reynolds
            pts = cond.points
            alphas = [p.alpha_deg for p in pts]
            derivs = cond.derivatives

            lines.append(f"* -------------------------------------------------------------")
            lines.append(f"* FLIGHT CONDITION {cond_idx}: MACH={mach:.3f}, RE={reynolds:.2e}")
            lines.append(f"* -------------------------------------------------------------")

            # 1. FLTCON NAMELIST
            alpha_str_chunks = []
            chunk = []
            for a in alphas:
                chunk.append(f"{a:.2f}")
                if len(chunk) == 8:
                    alpha_str_chunks.append(", ".join(chunk))
                    chunk = []
            if chunk:
                alpha_str_chunks.append(", ".join(chunk))

            lines.append(f" $FLTCON NMACH=1.0, MACH(1)={mach:.3f},")
            lines.append(f"         RNNUB(1)={reynolds:.3E},")
            lines.append(f"         NALPHA={float(len(alphas)):.1f},")
            for i, c_str in enumerate(alpha_str_chunks):
                prefix = f"         ALSCHD({i*8 + 1})="
                suffix = "," if i < len(alpha_str_chunks) - 1 else "$"
                lines.append(f"{prefix}{c_str}{suffix}")

            # 2. OPTINS & SYNTHS NAMELISTS
            lines.append(f" $OPTINS SREF=1.0, CBARR=1.0, BLREF=1.0$")
            lines.append(f" $SYNTHS XCG=0.25, ZCG=0.0, XW=0.0, ZW=0.0$")

            # 3. AIRFOIL DEFINITION
            clean_name = db.geometry_name.upper().replace(" ", "-")
            if "NACA" in clean_name and any(char.isdigit() for char in clean_name):
                # Standard NACA code designation for DATCOM
                code = clean_name.replace("NACA-", "").replace("NACA", "")
                if len(code) == 4 and code.isdigit():
                    lines.append(f" $WGPLNF CHRDHT=1.0, TYPE=1.0$")
                    lines.append(f" $NACA-4-{code}$")
                else:
                    lines.append(f" $WGPLNF CHRDHT=1.0$")
                    lines.append(f" $AIRFOIL NAME='{clean_name}'$")
            else:
                lines.append(f" $WGPLNF CHRDHT=1.0$")
                lines.append(f" $AIRFOIL NAME='{clean_name}'$")

            # 4. TABULATED POLAR SECTION
            lines.append(f"*")
            lines.append(f"* DERIVATIVES: CL_ALPHA={derivs.cl_alpha_per_rad:.3f}/RAD, ALPHA_0L={derivs.alpha_zero_lift_deg:.2f} DEG")
            lines.append(f"*              CD0={derivs.cd_0:.5f}, L/D_MAX={derivs.l_over_d_max:.2f} (AT ALPHA={derivs.alpha_cruise_deg:.1f} DEG)")
            lines.append(f"*              CM_ALPHA={derivs.cm_alpha_per_rad:.4f}/RAD, X_AC/C={derivs.aerodynamic_center_x_over_c:.3f}")
            lines.append(f"*")
            lines.append(f"*    ALPHA        CL          CD          CM         L/D")
            for p in pts:
                lines.append(
                    f"   {p.alpha_deg:7.2f}    {p.cl:8.4f}    {p.cd:9.5f}    {p.cm:8.4f}    {p.l_over_d:7.2f}"
                )
            lines.append(f"*")

        lines.append(f"NEXT CASE")
        lines.append(f"")
        return "\n".join(lines)

    @classmethod
    def export_shabp(cls, db: AeroDatabase) -> str:
        """
        Exports NASA S/HABP (Supersonic/Hypersonic Arbitrary-Body Program) polar format.
        """
        lines: List[str] = []
        lines.append(f"# NASA S/HABP TABULATED AERODYNAMIC COEFFICIENT FILE")
        lines.append(f"# AIRFRAME CONFIGURATION: {db.geometry_name.upper()}")
        lines.append(f"# DATABASE ID: {db.db_id}")
        lines.append(f"# GENERATED AT UTC: {db.created_at_utc}")
        lines.append(f"# PROVENANCE MERKLE: {db.provenance_hash}")
        lines.append(f"# REFERENCE CHORD: {db.chord_m} M")
        lines.append(f"#")

        for cond in db.polars:
            d = cond.derivatives
            lines.append(f"$TABLE")
            lines.append(f"TITLE = '{db.geometry_name} MACH={cond.mach:.2f} RE={cond.reynolds:.1e}'")
            lines.append(f"MACH = {cond.mach:.3f}")
            lines.append(f"REYNOLDS = {cond.reynolds:.3e}")
            lines.append(f"CL_ALPHA = {d.cl_alpha_per_rad:.4f}  # per radian")
            lines.append(f"ALPHA_0L = {d.alpha_zero_lift_deg:.2f}  # degrees")
            lines.append(f"CD_0 = {d.cd_0:.5f}")
            lines.append(f"LD_MAX = {d.l_over_d_max:.2f}")
            lines.append(f"CM_ALPHA = {d.cm_alpha_per_rad:.4f}  # per radian")
            lines.append(f"X_AC = {d.aerodynamic_center_x_over_c:.3f}  # fraction of chord")
            lines.append(f"STABILITY = '{d.longitudinal_stability}'")
            lines.append(f"POINTS = {len(cond.points)}")
            lines.append(f"#  ALPHA_DEG       CL          CD          CM         L_OVER_D   EPISTEMIC_STATUS")
            for p in cond.points:
                lines.append(
                    f"  {p.alpha_deg:9.3f}   {p.cl:10.5f}  {p.cd:10.6f}  {p.cm:10.5f}   {p.l_over_d:9.2f}   {p.epistemic_status}"
                )
            lines.append(f"$ENDTABLE")
            lines.append(f"#")

        return "\n".join(lines)

    @classmethod
    def export_6dof_csv(cls, db: AeroDatabase) -> str:
        """
        Exports clean CSV lookup tables formatted for 6-DOF simulation models
        (Simulink Aerospace Blockset, MATLAB, ArduPilot, PX4, JSBSim).
        """
        output = io.StringIO()
        headers = [
            "mach",
            "reynolds",
            "alpha_deg",
            "alpha_rad",
            "cl",
            "cd",
            "cm",
            "l_over_d",
            "cl_alpha_per_rad",
            "cm_alpha_per_rad",
            "cd_0",
            "x_ac_over_c",
            "provenance_hash",
        ]
        output.write(",".join(headers) + "\n")

        for cond in db.polars:
            d = cond.derivatives
            for p in cond.points:
                alpha_rad = round(math.radians(p.alpha_deg), 5)
                row = [
                    f"{cond.mach:.3f}",
                    f"{cond.reynolds:.0f}",
                    f"{p.alpha_deg:.2f}",
                    f"{alpha_rad:.5f}",
                    f"{p.cl:.4f}",
                    f"{p.cd:.5f}",
                    f"{p.cm:.4f}",
                    f"{p.l_over_d:.2f}",
                    f"{d.cl_alpha_per_rad:.3f}",
                    f"{d.cm_alpha_per_rad:.4f}",
                    f"{d.cd_0:.5f}",
                    f"{d.aerodynamic_center_x_over_c:.3f}",
                    f"{db.provenance_hash[:16]}",
                ]
                output.write(",".join(row) + "\n")

        return output.getvalue()

    @classmethod
    def export_json(cls, db: AeroDatabase) -> Dict[str, Any]:
        """
        Exports native structured JSON schema.
        """
        return db.model_dump()
