"""
AASI Stage-10 Empirical Validation Ledger.
Machine-readable canonical record for each investigation attempt.

Status semantics (mutually exclusive):
    PLANNED     — User intent recorded but no case generated
    STAGED      — OpenFOAM case deck + notebook generated, awaiting operator
    EXECUTED    — Solver was invoked externally; log exists
    VERIFIED    — Archive imported and passed full verification audit
    FAILED      — Solver diverged / crashed / timed out
    INCOMPLETE  — Archive exists but missing critical evidence
    SYNTHETIC   — Data was generated by surrogate/analytical (not empirical)
    USER_PROVIDED — Operator uploaded data outside AASI automation
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from enum import Enum
from pathlib import Path
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class LedgerStatus(str, Enum):
    PLANNED = "PLANNED"
    STAGED = "STAGED"
    EXECUTED = "EXECUTED"
    VERIFIED = "VERIFIED"
    FAILED = "FAILED"
    INCOMPLETE = "INCOMPLETE"
    SYNTHETIC = "SYNTHETIC"
    USER_PROVIDED = "USER_PROVIDED"


class LedgerEntry(BaseModel):
    """Canonical provenance record for a single investigation attempt."""
    investigation_id: str
    job_id: str
    geometry_identity: str
    geometry_hash: Optional[str] = None
    case_hash: Optional[str] = None
    mesh_hash: Optional[str] = None

    # Operating conditions
    conditions: Dict[str, Any] = Field(default_factory=dict)
    requested_parameters: Dict[str, Any] = Field(default_factory=dict)
    executed_parameters: Dict[str, Any] = Field(default_factory=dict)

    # Status
    verification_status: LedgerStatus = LedgerStatus.PLANNED
    epistemic_class: Optional[str] = None

    # Execution receipts
    execution_receipt: Optional[Dict[str, Any]] = None
    result_receipt: Optional[Dict[str, Any]] = None
    archive_hash: Optional[str] = None

    # Retry / repair chain
    parent_attempt: Optional[str] = None      # job_id of parent attempt
    attempt_number: int = 1
    diagnosis: Optional[str] = None
    repair_status: Optional[str] = None

    # Timestamps
    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


class EmpiricalValidationLedger:
    """Persistent, append-only ledger of all investigation attempts.

    Enforces that no entry can regress from VERIFIED to a lower state,
    and that STAGED cannot become VERIFIED without passing through EXECUTED.
    """

    VALID_PROMOTIONS = {
        LedgerStatus.PLANNED: {LedgerStatus.STAGED, LedgerStatus.FAILED},
        LedgerStatus.STAGED: {LedgerStatus.EXECUTED, LedgerStatus.FAILED},
        LedgerStatus.EXECUTED: {LedgerStatus.VERIFIED, LedgerStatus.FAILED, LedgerStatus.INCOMPLETE},
        LedgerStatus.VERIFIED: set(),  # Terminal
        LedgerStatus.FAILED: {LedgerStatus.STAGED},  # Retry re-stages
        LedgerStatus.INCOMPLETE: {LedgerStatus.FAILED},
        LedgerStatus.SYNTHETIC: set(),
        LedgerStatus.USER_PROVIDED: {LedgerStatus.VERIFIED, LedgerStatus.INCOMPLETE},
    }

    def __init__(self, ledger_path: Optional[Path] = None):
        self._path = ledger_path or Path("data/empirical_ledger.json")
        self._entries: Dict[str, LedgerEntry] = {}
        self._load()

    def _load(self):
        if self._path.exists():
            try:
                data = json.loads(self._path.read_text(encoding="utf-8"))
                for key, entry_dict in data.items():
                    self._entries[key] = LedgerEntry(**entry_dict)
            except Exception:
                pass

    def _save(self):
        self._path.parent.mkdir(parents=True, exist_ok=True)
        data = {k: v.model_dump() for k, v in self._entries.items()}
        content = json.dumps(data, indent=2, default=str)
        # Create atomic backup if file already exists
        if self._path.exists():
            bak_path = self._path.with_suffix(".json.bak")
            try:
                bak_path.write_text(self._path.read_text(encoding="utf-8"), encoding="utf-8")
            except Exception:
                pass
        # Atomic write via temp file
        temp_path = self._path.with_suffix(".json.tmp")
        temp_path.write_text(content, encoding="utf-8")
        temp_path.replace(self._path)

    def record(self, entry: LedgerEntry) -> LedgerEntry:
        """Record or update a ledger entry. Validates state transitions and enforces immutability."""
        key = entry.job_id
        if key in self._entries:
            existing = self._entries[key]
            # Immutability Guard: If existing entry is VERIFIED, critical scientific values cannot be mutated
            if existing.verification_status == LedgerStatus.VERIFIED:
                if (
                    existing.case_hash != entry.case_hash
                    or existing.archive_hash != entry.archive_hash
                    or existing.geometry_identity != entry.geometry_identity
                    or existing.result_receipt != entry.result_receipt
                    or entry.verification_status != LedgerStatus.VERIFIED
                ):
                    raise ValueError(
                        f"CRITICAL IMMUTABILITY VIOLATION: Cannot mutate verified empirical entry {key}. "
                        f"Physical results, geometry, and cryptographic digests are permanently sealed."
                    )
            allowed = self.VALID_PROMOTIONS.get(existing.verification_status, set())
            if entry.verification_status != existing.verification_status:
                if entry.verification_status not in allowed:
                    raise ValueError(
                        f"Invalid ledger transition for {key}: "
                        f"{existing.verification_status.value} -> {entry.verification_status.value}. "
                        f"Allowed: {[s.value for s in allowed]}"
                    )
        entry.updated_at = datetime.now(timezone.utc).isoformat()
        self._entries[key] = entry
        self._save()
        return entry

    def get(self, job_id: str) -> Optional[LedgerEntry]:
        return self._entries.get(job_id)

    def list_all(self) -> List[LedgerEntry]:
        return list(self._entries.values())

    def get_verified_count(self) -> int:
        return sum(1 for e in self._entries.values() if e.verification_status == LedgerStatus.VERIFIED)

    def get_failed_count(self) -> int:
        return sum(1 for e in self._entries.values() if e.verification_status == LedgerStatus.FAILED)

    def export_summary(self) -> List[Dict[str, Any]]:
        return [e.model_dump() for e in self._entries.values()]

    def verify_baseline_integrity(self) -> bool:
        """Verifies that Stage-10 certified runs remain intact and unmodified."""
        certified_jobs = ["JOB-54893A97F845", "JOB-80DB5B487D99", "JOB-0CFE9D358807"]
        for jid in certified_jobs:
            entry = self.get(jid)
            if not entry or entry.verification_status != LedgerStatus.VERIFIED:
                return False
        return True

