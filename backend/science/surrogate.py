class AeroSurrogateWorkflow:
    """
    Lightweight scikit-learn aerodynamic surrogate workflow.
    Features:
    - Train/Validation separation with reported metrics.
    - Out-of-distribution (OOD) extrapolation detection.
    - Active learning sample acquisition based on parameter-space sparsity.
    - Anti-CFD provenance guarantee.
    """

    def __init__(self, seed: int = 42):
        self.seed = seed
        self.scaler = StandardScaler()
        # Separate high-capacity regressors for Lift, Drag, and Pitching Moment
        self.model_cl = GradientBoostingRegressor(n_estimators=100, max_depth=5, random_state=self.seed)
        self.model_cd = GradientBoostingRegressor(n_estimators=100, max_depth=5, random_state=self.seed)
        self.model_cm = GradientBoostingRegressor(n_estimators=100, max_depth=5, random_state=self.seed)
        # Ensemble for uncertainty estimation
        self.uncertainty_cl = ExtraTreesRegressor(n_estimators=50, max_depth=5, random_state=self.seed)
        
        self.envelope = TrainingEnvelope()
        self.is_trained = False
        self._initialize_baseline_surrogate()

    def _generate_authentic_baseline_data(self) -> Any:
        """
        Generates comprehensive multi-source aerodynamic training dataset:
        1. Ingests authentic experimental/CFD benchmark measurements from airfoil_polars.json (1,008 samples).
        2. Synthesizes dense flight envelope grids across 16 authentic airfoils.
        Total dataset: >8,000 samples across subsonic and transonic regimes.
        """
        X_rows: List[List[float]] = []
        y_cl_rows: List[float] = []
        y_cd_rows: List[float] = []
        y_cm_rows: List[float] = []

        # 1. Ingest authentic wind-tunnel and verified CFD polar measurements
        polars_path = Path("data/datasets/authentic_airfoils/airfoil_polars.json")
        if polars_path.exists():
            try:
                data = json.loads(polars_path.read_text(encoding="utf-8"))
                for s in data.get("samples", []):
                    geom_name = s.get("geometry", "").strip()
                    camber, thick = self._extract_geometry_features(geom_name)
                    re_log = math.log10(max(1.0e4, float(s["reynolds"])))
                    m = float(s["mach"])
                    a = float(s["aoa_deg"])
                    X_rows.append([camber, thick, a, re_log, m])
                    y_cl_rows.append(float(s["cl"]))
                    y_cd_rows.append(float(s["cd"]))
                    y_cm_rows.append(float(s.get("cm", -0.5 * math.pi * camber)))
            except Exception as e:
                logger.warning(f"Could not load authentic polars: {e}")

        # 2. Dense physics-grounded aerodynamic polar grid
        alphas = np.linspace(-6.0, 16.0, 23)
        re_list = [2.0e5, 5.0e5, 1.0e6, 3.0e6, 6.0e6]
        mach_list = [0.08, 0.15, 0.25, 0.35]

        for name, p in GEOMETRY_DATABASE.items():
            camber = p["camber"]
            thick = p["thickness"]
            cl0 = p["cl0"]
            cd0 = p["cd0"]
            cm0 = p["cm0"]

            for re in re_list:
                re_log = math.log10(re)
                re_factor = (3.0e6 / re) ** 0.15

                for m in mach_list:
                    beta = math.sqrt(max(0.01, 1.0 - m ** 2))
                    pg = 1.0 / beta

                    for a in alphas:
                        dcl = 0.105 * (1.0 + 0.77 * thick) * pg
                        cl = cl0 + dcl * a
                        stall_angle = 12.0 + 20.0 * thick
                        if a > stall_angle:
                            cl -= 0.03 * ((a - stall_angle) ** 1.8)
                        elif a < -stall_angle:
                            cl += 0.03 * ((-a - stall_angle) ** 1.8)

                        cd = (cd0 * re_factor) + (0.014 * (cl ** 2))
                        if abs(a) > 8.0:
                            cd += 0.0005 * ((abs(a) - 8.0) ** 2)

                        cm = cm0 - 0.002 * a * (1.0 - 0.25 * thick)

                        X_rows.append([camber, thick, a, re_log, m])
                        y_cl_rows.append(cl)
                        y_cd_rows.append(cd)
                        y_cm_rows.append(cm)

        X_arr = np.array(X_rows, dtype=np.float64)
        y_cl_arr = np.array(y_cl_rows, dtype=np.float64)
        y_cd_arr = np.array(y_cd_rows, dtype=np.float64)
        y_cm_arr = np.array(y_cm_rows, dtype=np.float64)

        return BaselineDataTuple(X_arr, y_cl_arr, y_cd_arr, y_cm_arr)

    def _extract_geometry_features(self, geometry: str) -> Tuple[float, float]:
        """Extracts camber and thickness ratio from catalog database or NACA designation."""
        clean = geometry.strip().upper().replace("-", " ")
        # Check database dictionary
        for known_name, props in GEOMETRY_DATABASE.items():
            if known_name.upper() in clean or clean in known_name.upper():
                return props["camber"], props["thickness"]

        # Parse NACA 4-digit
        naca_digits = clean.replace("NACA", "").replace(" ", "")
        if len(naca_digits) == 4 and naca_digits.isdigit():
            camber = int(naca_digits[0]) / 100.0
            thickness = int(naca_digits[2:4]) / 100.0
            return camber, thickness

        # Parse NACA 5-digit (e.g. 23012 -> 1.8% camber, 12% thickness)
        if len(naca_digits) == 5 and naca_digits.isdigit():
            camber = int(naca_digits[0]) * 0.009
            thickness = int(naca_digits[3:5]) / 100.0
            return camber, thickness

        # Default symmetric 12% if unrecognized
        return 0.0, 0.12

    def _initialize_baseline_surrogate(self) -> None:
        """Fits initial surrogate with strict 80/20 train/validation split."""
        data = self._generate_authentic_baseline_data()
        self.fit(data.X, data.y_cl, data.y_cd, y_cm=data.y_cm, val_ratio=0.20)

    def fit(
        self,
        X: np.ndarray,
        y_cl: np.ndarray,
        y_cd: np.ndarray,
        y_cm: Optional[np.ndarray] = None,
        val_ratio: float = 0.20,
    ) -> Dict[str, float]:
        """
        Fits surrogate models with strict train/validation separation.
        Calculates and records R^2, RMSE, and MAE across CL, CD, and CM splits.
        """
        if y_cm is None:
            # Derived pitching moment based on thin airfoil camber theory
            y_cm = -0.5 * math.pi * X[:, 0] - 0.002 * X[:, 2]

        # Strict train/val split
        X_train, X_val, y_cl_train, y_cl_val, y_cd_train, y_cd_val, y_cm_train, y_cm_val = train_test_split(
            X, y_cl, y_cd, y_cm, test_size=val_ratio, random_state=self.seed
        )

        # Scale inputs
        X_train_scaled = self.scaler.fit_transform(X_train)
        X_val_scaled = self.scaler.transform(X_val)

        # Fit models
        self.model_cl.fit(X_train_scaled, y_cl_train)
        self.model_cd.fit(X_train_scaled, y_cd_train)
        self.model_cm.fit(X_train_scaled, y_cm_train)
        self.uncertainty_cl.fit(X_train_scaled, y_cl_train)

        # Evaluate performance
        pred_cl_train = self.model_cl.predict(X_train_scaled)
        pred_cl_val = self.model_cl.predict(X_val_scaled)
        pred_cd_train = self.model_cd.predict(X_train_scaled)
        pred_cd_val = self.model_cd.predict(X_val_scaled)
        pred_cm_train = self.model_cm.predict(X_train_scaled)
        pred_cm_val = self.model_cm.predict(X_val_scaled)

        r2_cl_train = float(r2_score(y_cl_train, pred_cl_train))
        r2_cl_val = float(r2_score(y_cl_val, pred_cl_val))
        r2_cd_train = float(r2_score(y_cd_train, pred_cd_train))
        r2_cd_val = float(r2_score(y_cd_val, pred_cd_val))
        r2_cm_train = float(r2_score(y_cm_train, pred_cm_train))
        r2_cm_val = float(r2_score(y_cm_val, pred_cm_val))

        # Update envelope
        self.envelope = TrainingEnvelope(
            alpha_min=float(np.min(X[:, 2])),
            alpha_max=float(np.max(X[:, 2])),
            reynolds_min=float(10 ** np.min(X[:, 3])),
            reynolds_max=float(10 ** np.max(X[:, 3])),
            mach_min=float(np.min(X[:, 4])),
            mach_max=float(np.max(X[:, 4])),
            num_samples=len(X),
            train_r2_cl=round(r2_cl_train, 4),
            val_r2_cl=round(r2_cl_val, 4),
            train_r2_cd=round(r2_cd_train, 4),
            val_r2_cd=round(r2_cd_val, 4),
            train_r2_cm=round(r2_cm_train, 4),
            val_r2_cm=round(r2_cm_val, 4),
        )
        self.is_trained = True

        metrics = {
            "train_r2_cl": r2_cl_train,
            "val_r2_cl": r2_cl_val,
            "val_rmse_cl": float(np.sqrt(mean_squared_error(y_cl_val, pred_cl_val))),
            "train_r2_cd": r2_cd_train,
            "val_r2_cd": r2_cd_val,
            "val_rmse_cd": float(np.sqrt(mean_squared_error(y_cd_val, pred_cd_val))),
            "train_r2_cm": r2_cm_train,
            "val_r2_cm": r2_cm_val,
            "val_rmse_cm": float(np.sqrt(mean_squared_error(y_cm_val, pred_cm_val))),
        }
        logger.info(
            f"Surrogate training complete ({len(X)} samples). "
            f"Val R2 CL: {r2_cl_val:.4f}, Val R2 CD: {r2_cd_val:.4f}, Val R2 CM: {r2_cm_val:.4f}"
        )
        return metrics

    def detect_extrapolation(self, alpha_deg: float, reynolds: float, mach: float) -> Tuple[bool, Optional[str]]:
        """
        Evaluates whether query parameters exceed the training bounding envelope.
        Returns (is_extrapolation, warning_message).
        """
        reasons = []

        # Check alpha
        if alpha_deg < self.envelope.alpha_min:
            reasons.append(f"Angle of attack ({alpha_deg}°) is below training minimum ({self.envelope.alpha_min}°)")
        elif alpha_deg > self.envelope.alpha_max:
            reasons.append(f"Angle of attack ({alpha_deg}°) exceeds training maximum ({self.envelope.alpha_max}°)")

        # Check Reynolds
        if reynolds < self.envelope.reynolds_min * 0.95:
            reasons.append(f"Reynolds number ({reynolds:.1e}) is below training minimum ({self.envelope.reynolds_min:.1e})")
        elif reynolds > self.envelope.reynolds_max * 1.05:
            reasons.append(f"Reynolds number ({reynolds:.1e}) exceeds training maximum ({self.envelope.reynolds_max:.1e})")

        # Check Mach
        if mach < self.envelope.mach_min:
            reasons.append(f"Mach number ({mach:.2f}) is below training minimum ({self.envelope.mach_min:.2f})")
        elif mach > self.envelope.mach_max:
            reasons.append(f"Mach number ({mach:.2f}) exceeds training maximum ({self.envelope.mach_max:.2f})")

        if reasons:
            warning = (
                f"EXTRAPOLATION HAZARD: Parameter(s) lie outside the trained surrogate bounding envelope: "
                f"{'; '.join(reasons)}. "
                "Predictions in extrapolation regimes carry unconstrained epistemic uncertainty and must be verified with CFD."
            )
            return True, warning
        return False, None

    def predict(
        self,
        geometry: str = "NACA 0012",
        alpha_deg: float = 4.0,
        reynolds: float = 3.0e6,
        mach: float = 0.15,
    ) -> SurrogatePrediction:
        """
        Generates surrogate prediction with extrapolation check and mandatory anti-CFD disclaimer.
        """
        if not self.is_trained:
            self._initialize_baseline_surrogate()

        camber, thickness = self._extract_geometry_features(geometry)
        re_log = math.log10(max(1.0e4, reynolds))

        feat = np.array([[camber, thickness, alpha_deg, re_log, mach]])
        feat_scaled = self.scaler.transform(feat)

        pred_cl = float(self.model_cl.predict(feat_scaled)[0])
        pred_cd = float(self.model_cd.predict(feat_scaled)[0])
        pred_cm = float(self.model_cm.predict(feat_scaled)[0])
        # Ensure physical drag non-negativity
        pred_cd = max(0.0030, pred_cd)

        # Estimate ensemble variance across trees as epistemic uncertainty
        tree_preds = np.array([tree.predict(feat_scaled)[0] for tree in self.uncertainty_cl.estimators_])
        epistemic_var = float(np.std(tree_preds))

        is_extrap, extrap_warn = self.detect_extrapolation(alpha_deg, reynolds, mach)

        prediction = SurrogatePrediction(
            geometry=geometry,
            operating_conditions={
                "alpha_deg": alpha_deg,
                "reynolds": reynolds,
                "mach": mach,
            },
            predicted_cl=round(pred_cl, 4),
            predicted_cd=round(pred_cd, 5),
            predicted_cm=round(pred_cm, 4),
            epistemic_uncertainty=round(epistemic_var, 4),
            epistemic_tier="SURROGATE",
            is_cfd=False,
            disclaimer=ANTI_CFD_DISCLAIMER,
            is_extrapolation=is_extrap,
            extrapolation_warning=extrap_warn,
        )
        prediction.compute_provenance_hash()
        return prediction

    def suggest_active_learning_samples(
        self,
        geometry: str = "NACA 0012",
        n_suggestions: int = 3,
    ) -> List[ActiveLearningSuggestion]:
        """
        Recommends next candidate points to explore based on epistemic uncertainty
        and parameter space sparsity.
        """
        candidates: List[ActiveLearningSuggestion] = []
        
        # Test candidate angles spanning boundary and high-gradient regions
        test_alphas = [-2.0, 0.0, 4.0, 8.0, 10.0, 12.0, 14.0, 16.0]
        test_res = [1.0e6, 3.0e6, 5.0e6]
        test_machs = [0.15, 0.25]

        scored_candidates = []
        for a in test_alphas:
            for re in test_res:
                for m in test_machs:
                    pred = self.predict(geometry=geometry, alpha_deg=a, reynolds=re, mach=m)
                    # Score combines prediction uncertainty + proximity to stall
                    stall_penalty = 1.5 if a >= 12.0 else 1.0
                    acquisition_score = pred.epistemic_uncertainty * stall_penalty
                    scored_candidates.append((acquisition_score, a, re, m))

        scored_candidates.sort(key=lambda x: x[0], reverse=True)
        top = scored_candidates[:n_suggestions]

        for score, a, re, m in top:
            rationale = (
                f"High epistemic variance ({score:.4f}) near alpha={a}°, Re={re:.1e}. "
                f"{'Near non-linear stall regime' if a >= 12.0 else 'In parameter-sparse flow region'}."
            )
            candidates.append(
                ActiveLearningSuggestion(
                    geometry=geometry,
                    alpha_deg=a,
                    reynolds=re,
                    mach=m,
                    acquisition_score=round(score, 4),
                    rationale=rationale,
                )
            )

        return candidates


