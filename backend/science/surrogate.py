class SurrogatePrediction(BaseModel):
    """
    Result of a surrogate aerodynamic evaluation.
    Enforces strict anti-CFD labeling rule.
    """
    geometry: str
    operating_conditions: Dict[str, float]
    predicted_cl: float
    predicted_cd: float
    predicted_cm: Optional[float] = None
    epistemic_uncertainty: float = Field(
        default=0.0,
        description="Statistical ensemble variance / parameter sparsity metric (NOT physical error bar)",
    )
    
    # Anti-CFD Epistemic Guardrails (Prompt 9)
    epistemic_tier: str = Field(
        default="SURROGATE",
        description="Immutable epistemic tier. Never CFD.",
    )
    is_cfd: bool = Field(
        default=False,
        description="Must always be False. Never label surrogate predictions as CFD.",
    )
    disclaimer: str = Field(default=ANTI_CFD_DISCLAIMER)

    # Extrapolation Detection
    is_extrapolation: bool = Field(
        default=False,
        description="True if query parameters lie outside the surrogate training bounding envelope.",
    )
    extrapolation_warning: Optional[str] = Field(
        default=None,
        description="Scientific warning emitted when operating in extrapolation regimes.",
    )

    provenance_hash: str = ""
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())

    @model_validator(mode="after")
    def verify_anti_cfd_integrity(self) -> "SurrogatePrediction":
        """
        CRITICAL GOVERNANCE RULE:
        Surrogate predictions MUST NEVER be labeled as CFD, SIMULATED, or VERIFIED.
        """
        if self.is_cfd:
            raise ValueError(
                "CRITICAL PROVENANCE VIOLATION: Surrogate predictions cannot be labeled as CFD! "
                "is_cfd must strictly be False."
            )
        if self.epistemic_tier.upper() in {"CFD", "LIVE_CFD", "SIMULATED", "VERIFIED", "EXPERIMENTAL"}:
            raise ValueError(
                f"CRITICAL PROVENANCE VIOLATION: Invalid tier '{self.epistemic_tier}' for surrogate output. "
                "Must be 'SURROGATE'."
            )
        return self

    def compute_provenance_hash(self) -> str:
        payload = {
            "geometry": self.geometry.strip().upper(),
            "conditions": self.operating_conditions,
            "predicted_cl": round(self.predicted_cl, 5),
            "predicted_cd": round(self.predicted_cd, 5),
            "is_extrapolation": self.is_extrapolation,
            "epistemic_tier": self.epistemic_tier,
            "is_cfd": self.is_cfd,
        }
        raw = json.dumps(payload, sort_keys=True)
        self.provenance_hash = hashlib.sha256(raw.encode("utf-8")).hexdigest()
        return self.provenance_hash


