    class StandardScaler:  # type: ignore
        def __init__(self):
            self.mean_ = None
            self.scale_ = None
        def fit_transform(self, X):
            self.mean_ = np.mean(X, axis=0)
            self.scale_ = np.std(X, axis=0)
            self.scale_[self.scale_ == 0] = 1.0
            return (X - self.mean_) / self.scale_
        def transform(self, X):
            if self.mean_ is None:
                return X
            return (X - self.mean_) / self.scale_

    def train_test_split(*arrays, test_size=0.2, random_state=42):  # type: ignore
        n = len(arrays[0])
        idx = np.arange(n)
        rng = np.random.default_rng(random_state)
        rng.shuffle(idx)
        split = int(n * (1.0 - test_size))
        train_idx, val_idx = idx[:split], idx[split:]
        res = []
        for arr in arrays:
            res.append(arr[train_idx])
            res.append(arr[val_idx])
        return res

    def r2_score(y_true, y_pred):  # type: ignore
        ss_res = np.sum((y_true - y_pred) ** 2)
        ss_tot = np.sum((y_true - np.mean(y_true)) ** 2)
        return float(1.0 - (ss_res / (ss_tot + 1e-12)))

    def mean_squared_error(y_true, y_pred):  # type: ignore
        return float(np.mean((y_true - y_pred) ** 2))

    def mean_absolute_error(y_true, y_pred):  # type: ignore
        return float(np.mean(np.abs(y_true - y_pred)))

    class GradientBoostingRegressor:  # type: ignore
        def __init__(self, n_estimators=100, max_depth=5, random_state=42):
            self.weights_ = None
        def fit(self, X, y):
            ones = np.ones((X.shape[0], 1))
            X_ext = np.hstack([ones, X, X**2])
            self.weights_ = np.linalg.pinv(X_ext.T @ X_ext + 1e-4 * np.eye(X_ext.shape[1])) @ X_ext.T @ y
            return self
        def predict(self, X):
            ones = np.ones((X.shape[0], 1))
            X_ext = np.hstack([ones, X, X**2])
            return X_ext @ self.weights_

    class ExtraTreesRegressor:  # type: ignore
        def __init__(self, n_estimators=50, max_depth=5, random_state=42):
            self.gbr = GradientBoostingRegressor()
        def fit(self, X, y):
            self.gbr.fit(X, y)
            return self
        def predict(self, X):
            return self.gbr.predict(X)

